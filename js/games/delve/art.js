function hash(x, y, k = 0) { let h = (x * 374761393 + y * 668265263 + k * 1442695041) | 0; h = (h ^ (h >>> 13)) * 1274126177; return ((h ^ (h >>> 16)) >>> 0) / 4294967295; }
export { hash };

const cache = new Map();
// The sprite at 1 pixel per letter (with its outline), as a canvas.
export function sprite(id) {
  if (cache.has(id)) return cache.get(id);
  const rows = SPR[id];
  if (!rows) return null;
  const w = Math.max(...rows.map((r) => r.length)) + 2, h = rows.length + 2;
  const at = (x, y) => (rows[y - 1] || '')[x - 1] || '.';
  const cv = document.createElement('canvas'); cv.width = w; cv.height = h;
  const g = cv.getContext('2d');
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const ch = at(x, y);
    let col = null;
    if (ch === '.') {
      if ([[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => at(x + dx, y + dy) !== '.')) col = OUTLINE;
    } else if (FLAT[ch]) col = FLAT[ch];
    else {
      const m = ch.toLowerCase(), ramp = RAMP[m];
      if (!ramp) continue;
      const same = (dx, dy) => at(x + dx, y + dy).toLowerCase() === m;
      let t;
      if (ch !== m) t = 0;
      else if (!same(0, -1)) t = 2;
      else if (!same(1, 0) && !same(-1, 0)) t = 2; // 1px-wide parts (blades, staffs) stay bright
      else if (!same(1, 0) || !same(0, 1)) t = 0;
      else if (!same(-1, 0)) t = 2;
      else t = 1;
      if (ch === m && hash(x, y, id.length) < 0.12) t = Math.max(0, t - 1); // grime
      col = ramp[t];
    }
    if (col) { g.fillStyle = col; g.fillRect(x, y, 1, 1); }
  }
  cache.set(id, cv);
  return cv;
}

// A scaled-up copy (pixel-perfect), optionally mirrored, as a canvas.
const scaledCache = new Map();
export function scaled(id, s, flip = false) {
  const key = `${id}|${s}|${flip}`;
  if (scaledCache.has(key)) return scaledCache.get(key);
  const src = sprite(id);
  if (!src) return null;
  const cv = document.createElement('canvas');
  cv.width = src.width * s; cv.height = src.height * s;
  const g = cv.getContext('2d'); g.imageSmoothingEnabled = false;
  if (flip) { g.translate(cv.width, 0); g.scale(-1, 1); }
  g.drawImage(src, 0, 0, cv.width, cv.height);
  scaledCache.set(key, cv);
  return cv;
}

// A brand-new <canvas> element (for the phone, which needs its own copy per use).
export function spriteEl(id, s, flip = false) {
  const src = scaled(id, s, flip);
  const cv = document.createElement('canvas');
  if (!src) return cv;
  cv.width = src.width; cv.height = src.height;
  cv.getContext('2d').drawImage(src, 0, 0);
  cv.className = 'px';
  return cv;
}
